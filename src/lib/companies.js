const MAP = new Map();
for (const [company, domains] of Object.entries(C)) for (const d of domains.split(' ')) MAP.set(d, company);

// "stats.g.doubleclick.net" -> "Google" (walks up the domain); unknown -> null
export function companyOf(host) {
    let d = host;
    while (d) {
        const c = MAP.get(d);
        if (c) return c;
        const i = d.indexOf('.');
        if (i < 0) break;
        d = d.slice(i + 1);
    }
    return null;
}
